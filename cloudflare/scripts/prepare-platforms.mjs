import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PLATFORMS = ['netease', 'qqmusic'];

export async function preparePlatformModules({ projectDirectory, outputPath }) {
  const imports = [];
  const registries = [];
  let importIndex = 0;

  for (const platform of PLATFORMS) {
    const moduleDirectory = path.join(projectDirectory, 'platforms', platform, 'module');
    const files = (await fs.readdir(moduleDirectory))
      .filter((file) => file.endsWith('.js'))
      .sort();
    const entries = [];
    for (const file of files) {
      const identifier = `module${importIndex++}`;
      const relativePath = `../../platforms/${platform}/module/${file}`;
      imports.push(`import ${identifier} from ${JSON.stringify(relativePath)};`);
      entries.push(`    ${JSON.stringify(file.replace(/\.js$/i, '').replace(/_/g, '/'))}: ${identifier}`);
    }
    registries.push(`  ${JSON.stringify(platform)}: {\n${entries.join(',\n')}\n  }`);
  }

  const source = [
    '// Generated by cloudflare/scripts/prepare-platforms.mjs. Do not edit.',
    ...imports,
    '',
    'export const platformModules = {',
    registries.join(',\n'),
    '};',
    ''
  ].join('\n');
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, source, 'utf8');
  return importIndex;
}

async function main() {
  const projectDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
  const outputPath = path.join(projectDirectory, 'cloudflare', 'generated', 'platform-modules.js');
  const count = await preparePlatformModules({ projectDirectory, outputPath });
  console.log(`[cloudflare] 已静态打包 ${count} 个平台模块`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
