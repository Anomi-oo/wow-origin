import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { prepareLxSource } from '../../cloudflare/scripts/prepare-lx.mjs';
import { preparePlatformModules } from '../../cloudflare/scripts/prepare-platforms.mjs';

const projectDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const cloudflareGenerated = path.join(projectDirectory, 'cloudflare', 'generated');
const edgeOneGenerated = path.join(projectDirectory, 'edgeone', 'generated');

const [source, moduleCount] = await Promise.all([
  prepareLxSource({
    sourceUrl: process.env.EDGEONE_LX_SOURCE_URL || process.env.CF_LX_SOURCE_URL || '',
    outputPath: path.join(cloudflareGenerated, 'lx-source.ts')
  }),
  preparePlatformModules({
    projectDirectory,
    outputPath: path.join(cloudflareGenerated, 'platform-modules.js')
  })
]);

const [loginPageHtml, appJs, stylesCss] = await Promise.all([
  fs.readFile(path.join(projectDirectory, 'public', 'index.html'), 'utf8'),
  fs.readFile(path.join(projectDirectory, 'public', 'app.js'), 'utf8'),
  fs.readFile(path.join(projectDirectory, 'public', 'styles.css'), 'utf8')
]);
await fs.mkdir(edgeOneGenerated, { recursive: true });
await fs.writeFile(
  path.join(edgeOneGenerated, 'login-page.ts'),
  '// Generated by edgeone/scripts/prepare.mjs. Do not edit.\n' +
    `export const loginPageHtml = ${JSON.stringify(loginPageHtml)};\n` +
    `export const appJs = ${JSON.stringify(appJs)};\n` +
    `export const stylesCss = ${JSON.stringify(stylesCss)};\n`,
  'utf8'
);

console.log(
  `[edgeone] 洛雪全局源: ${source.enabled ? `${source.name || '未命名源'} (${source.digest.slice(0, 12)})` : '未配置'}`
);
console.log(`[edgeone] 平台模块: ${moduleCount}`);
console.log('[edgeone] 登录页 HTML 已内联');
